export const PLAYGROUND_LOCALES = ['en-US', 'zh-CN', 'zh-TW'] as const;
export type PlaygroundLocale = (typeof PLAYGROUND_LOCALES)[number];

const dictionaries: Record<PlaygroundLocale, PlaygroundMessages> = {
  'en-US': enUS,
  'zh-CN': zhCN,
  'zh-TW': zhTW,
};

export function isPlaygroundLocale(value: string): value is PlaygroundLocale {
  return (PLAYGROUND_LOCALES as readonly string[]).includes(value);
}

export function messagesFor(locale: PlaygroundLocale): PlaygroundMessages {
  return dictionaries[locale];
}

export function fill(template: string, values: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/g, (match, key: string) => {
    const value = values[key];
    return value === undefined ? match : String(value);
  });
}
